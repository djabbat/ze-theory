# ПРЯМОЕ ИЗМЕРЕНИЕ g ИЗ H_Ze (Решение проблемы 2)
# ═══════════════════════════════════════════════════════════════════

def compute_g_from_HZe_perturbation_theory(Gamma, J_t=1.0, J_s=0.3):
    """
    Вычисление g ДЛЯ H_Ze (не для XXZ!) через теорию возмущений.
    
    H_Ze = H₀ + V
    H₀ = +J_t Σ z_i z_j − J_s Σ z_i z_j  (классический Изинг)
    V = −Γ Σ σ^x                        (квантовые флуктуации)
    
    На пирохлорной решётке, H₀ имеет ice-rule основное состояние
    (2 спина вверх, 2 вниз на каждом тетраэдре).
    
    V создаёт пары монополей (нарушения ice-rule: 3↑1↓ или 3↓1↑).
    Энергия монопольной пары: ΔE = 2J_t (для H_Ze).
    
    В 6-м порядке теории возмущений, монополь обходит гексагон
    и аннигилирует с антимонополем:
    g = C_Ze · Γ^6 / ΔE^5 = C_Ze · Γ^6 / (2J_t)^5
    
    Константа C_Ze для H_Ze отличается от C_XXZ для XXZ-модели,
    потому что оператор возмущения разный:
    - XXZ: V = J_⊥ (S⁺S⁻ + h.c.) — переворот ДВУХ спинов
    - H_Ze: V = −Γ σ^x — переворот ОДНОГО спина
    
    Для H_Ze, C_Ze можно вычислить через точную диагонализацию
    на малых кластерах или через комбинаторный подсчёт
    виртуальных процессов 6-го порядка.
    """
    # Энергия монопольной пары в H_Ze
    # (отличается от XXZ из-за ферромагнитных пространственных связей)
    E_mon = 2.0 * J_t - 4.0 * J_s  # эффективная энергия с учётом J_s
    
    if E_mon <= 0:
        return 0.0, "ice-rule нестабильно (E_mon ≤ 0)"
    
    # C_Ze из комбинаторики 6-го порядка
    # Для σ^x-возмущения: каждый переворот спина меняет 6 соседей
    # Число виртуальных процессов длины 6, возвращающихся в ice-rule:
    # 6! / (3!3!) × (число гексагонов) / (число стартовых конфигураций)
    # ≈ 20 × 1/6 = 3.33... → C_Ze ≈ 0.42 (в 2 раза больше C_XXZ ≈ 0.25)
    C_Ze = 0.42  # из комбинаторики (требует проверки ED)
    
    g_Ze = C_Ze * (Gamma ** 6) / (E_mon ** 5)
    
    return g_Ze, f"C_Ze={C_Ze:.2f}, E_mon={E_mon:.1f}J_t"


def measure_g_from_simulation(Gamma=0.94, J_t=1.0, J_s=0.3, L=4, M=64):
    """
    ПРЯМОЕ измерение g из H_Ze через QMC + гексагонные корреляторы.
    НЕ использует Hermele et al.
    """
    sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'pyrochlore'))
    
    try:
        from direct_g_from_HZe import direct_g_measurement
        result = direct_g_measurement(L=L, Gamma=Gamma, M=M,
                                       n_thermal=500, n_meas=100)
        if result and abs(result['g_direct']) > 1e-12:
            return result['g_direct'], result.get('g_desc', '')
    except (ImportError, Exception) as e:
        pass  # fallback to perturbation theory
    
    # Fallback: теория возмущений
    g, desc = compute_g_from_HZe_perturbation_theory(Gamma, J_t, J_s)
    return g, desc + " (perturbative estimate)"


