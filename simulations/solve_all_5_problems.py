def estimate_large_scale_resources():
    """
    Оценка вычислительных ресурсов для L=16, M=64.
    
    Rust QMC v2.1:
    - N_spins = L³ × L_t × M = 16³ × 6 × 64 = 1,572,864 спинов
    - Wolff cluster: O(N) на обновление
    - Типичное время: ∼0.5 мкс/спин/шаг на современном CPU
    - Полная симуляция (10⁵ шагов): ∼1.5 × 10⁶ × 0.5 × 10⁻⁶ × 10⁵ ≈ 75,000 сек ≈ 21 час
    
    На GPU (CUDA): ускорение ∼10−50× → 0.4−2 часа.
    На HPC кластере (64 ядра): ∼20 минут.
    """
    L, M = 16, 64
    N = L**3 * 6 * M
    time_per_step_us = 0.5
    n_steps = 100_000
    total_sec = N * time_per_step_us * 1e-6 * n_steps
    total_hours = total_sec / 3600
    
    print("=" * 65)
    print("ОЦЕНКА РЕСУРСОВ: L={}, M={}".format(L, M))
    print("=" * 65)
    print(f"  Спинов: {N:,}")
    print(f"  Время (desktop): {total_hours:.1f} часов")
    print(f"  Время (GPU, 10x): {total_hours/10:.1f} часов")
    print(f"  Время (HPC 64 ядра): {total_hours/64*60:.0f} минут")
    print()
    print("  Rust QMC v2.1 поддерживает L и M как параметры.")
    print("  Команда: ze-qmc-4d -L 16 -m 64 -G 0.94 --auto-thermal")


