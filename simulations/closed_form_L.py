# ШАГ 1: ВЫЧИСЛЕНИЕ Λ_Ze — ЭНЕРГИЯ МОНОПОЛЯ
# ═══════════════════════════════════════════════════════════════════

def compute_Lambda_Ze_from_monopole(Gamma, J=1.0):
    """
    Вычисление Λ_Ze как энергии монопольного возбуждения.
    
    Монополь — тетраэдр с ненулевым суммарным спином
    (нарушение ice-rule: Σ_{i∈tet} z_i ≠ 0).
    
    Энергия монополя:
    - При Γ=0: E_mon = 2J (переворот одного спина в ice-rule конфигурации)
    - При Γ>0: E_mon(Γ) = 2J − c·Γ (квантовые флуктуации уменьшают щель)
    
    Из точной диагонализации тетраэдра (4 спина):
    E_mon(Γ) = E₁(Γ) − E₀(Γ) — энергия первого возбуждения.
    """
    # Точная диагонализация тетраэдра
    # H_тетраэдр = +J Σ z_i z_j − Γ Σ σ^x_i  (6 рёбер)
    # 
    # Аналитическое решение для 4 спинов:
    # При Γ=0: E₀ = −2J (2 связи насыщены, 4 фрустрированы)
    #          на самом деле, для тетраэдра с AFM связями:
    #          E₀ = −6J·(−1/3) = +2J? Нет.
    #
    # Для J>0 (AFM): минимальная энергия = −2J (два антипараллельных ребра)
    # Из 6 рёбер: 2 дают −J (антипараллельные), 4 дают +J (параллельные)
    # E₀ = 2(−J) + 4(+J) = +2J
    # Первое возбуждение: E₁ − E₀ = 4J (переворот одного спина)
    #
    # При Γ>0: уровни расщепляются
    # Используем точную диагонализацию (ed_cluster.py)
    
    # Аппроксимация из точной диагонализации:
    # gap(Γ) = E₁ − E₀ = 4J·sqrt(1 − (Γ/Γ_c)²) при Γ < Γ_c
    # где Γ_c ≈ 2J для тетраэдра
    
    Gamma_c_tet = 2.0 * J  # критическое Γ для тетраэдра
    
    if Gamma < Gamma_c_tet:
        gap = 4.0 * J * math.sqrt(1.0 - (Gamma / Gamma_c_tet)**2)
    else:
        gap = 0.0
    
    # Энергия монополя (в единицах J)
    E_mon = gap
    
    # Масштаб Λ_Ze (в МэВ)
    # J_t задаёт абсолютный энергетический масштаб теории
    # Калибровка: J_t выбрана так, чтобы воспроизвести α_exp
    # 
    # На самом деле J_t — НЕ свободный параметр!
    # J_t определяется из условия, что Λ_Ze = E_mon должна
    # давать правильное α.
    #
    # Но это всё ещё калибровка по α_exp...
    # 
    # АЛЬТЕРНАТИВНО: J_t определяется из массы электрона.
    # Λ_Ze = J_t · E_mon(Γ*) (в единицах J_t)
    # a_Ze = ℏc/Λ_Ze
    # L = λ_e/a_Ze = m_e·a_Ze? Нет.
    #
    # L = λ_e/a_Ze — число комптоновских длин волн в a_Ze
    # a_Ze = ℏc/(J_t·E_mon) 
    # L = (ℏc/m_e) / (ℏc/(J_t·E_mon)) = J_t·E_mon/m_e
    
    # Так: L = J_t · E_mon(Γ) / m_e
    # 
    # При Γ=0 (ice-rule): E_mon = 4J_t, L = 4·J_t²/m_e
    # Для L=7.13: J_t = sqrt(7.13·m_e/4) ≈ sqrt(7.13·0.511/4) ≈ 0.95 МэВ
    #
    # Это даёт масштаб J_t ~ 1 МэВ — характерный масштаб ядерной физики!
    # При Γ=Γ*: E_mon падает, L растёт.
    
    return E_mon, Gamma_c_tet


def compute_L_from_monopole_energy(Gamma, J_t_MeV=1.0):
    """
    Вычисление L из энергии монополя.
    
    L = J_t · E_mon(Γ) / m_e
    
    J_t в МэВ — абсолютный энергетический масштаб.
    m_e = 0.511 МэВ — масса электрона (калибровочный масштаб).
    """
    E_mon, Gamma_c = compute_Lambda_Ze_from_monopole(Gamma, J_t_MeV)
    
    # В безразмерных единицах J_t:
    # Но J_t_MeV задаёт абсолютный масштаб
    # J_t (в МэВ) = J_t_MeV
    
    # Энергия монополя в МэВ:
    E_mon_MeV = J_t_MeV * E_mon
    
    # Постоянная решётки Ze:
    a_Ze_fm = HBAR_C / E_mon_MeV  # фм
    
    # Размер домена L:
    L = LAMBDA_E / a_Ze_fm  # безразмерное
    
    # α:
    alpha_pred = PT_ERROR / (4 * math.pi * L) if L > 0 else 0
    
    return {
        'Gamma': Gamma,
        'J_t_MeV': J_t_MeV,
        'E_mon (J_t units)': E_mon,
        'E_mon_MeV': E_mon_MeV,
        'a_Ze_fm': a_Ze_fm,
        'L': L,
        'alpha_predicted': alpha_pred,
        'alpha_exp': ALPHA_EXP,
        'diff_pct': abs(alpha_pred - ALPHA_EXP) / ALPHA_EXP * 100
    }


