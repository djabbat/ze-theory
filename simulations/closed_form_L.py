# ШАГ 3: ВЫЧИСЛЕНИЕ Γ* ИЗ УСЛОВИЯ МИНИМУМА ДЕЙСТВИЯ
# ═══════════════════════════════════════════════════════════════════

def find_Gamma_star_from_action():
    """
    Вычисление Γ* из принципа наименьшего действия.
    
    Идея: агент Ze выбирает Γ так, чтобы минимизировать
    функционал действия S[Γ] = ∫ dt L(Γ).
    
    Лагранжиан агента:
    L(Γ) = P(T|v*) · E_mon(Γ) − S_agent(v*)
    
    Первый член: вероятность ошибки × цена ошибки (энергия монополя)
    Второй член: энтропия агента (мера свободы)
    
    Условие: dL/dΓ = 0 при Γ = Γ*.
    """
    print("=" * 65)
    print("ВЫЧИСЛЕНИЕ Γ* ИЗ ПРИНЦИПА НАИМЕНЬШЕГО ДЕЙСТВИЯ")
    print("=" * 65)
    
    # Сканируем Γ
    Gamma_range = np.linspace(0.1, 1.5, 200)
    
    best_L_val = float('inf')
    best_Gamma = None
    
    for Gamma in Gamma_range:
        E_mon, Gamma_c = compute_Lambda_Ze_from_monopole(Gamma, 1.0)
        
        # Лагранжиан: L = P(T) · E_mon − S_agent
        # Минимизируем L (принцип наименьшего действия)
        L_val = PT_ERROR * E_mon - 0.931  # S_agent(v*) ≈ 0.931
        
        if L_val < best_L_val:
            best_L_val = L_val
            best_Gamma = Gamma
    
    print(f"  L_min = {best_L_val:.4f} при Γ* = {best_Gamma:.4f}")
    print(f"  E_mon(Γ*) = {compute_Lambda_Ze_from_monopole(best_Gamma, 1.0)[0]:.4f} J_t")
    
    # Теперь вычисляем J_t из самосогласования
    J_t_MeV = find_Jt_from_selfconsistency(best_Gamma)
    
    # Вычисляем α
    E_mon, _ = compute_Lambda_Ze_from_monopole(best_Gamma, 1.0)
    L_final = J_t_MeV * E_mon / M_E
    alpha_final = PT_ERROR / (4 * math.pi * L_final) if L_final > 0 else 0
    
    print(f"\n  ★ ФИНАЛЬНЫЙ РЕЗУЛЬТАТ:")
    print(f"  Γ* = {best_Gamma:.4f}")
    print(f"  J_t = {J_t_MeV:.2f} МэВ")
    print(f"  E_mon = {J_t_MeV * E_mon:.2f} МэВ")
    print(f"  L = {L_final:.2f}")
    print(f"  α = {alpha_final:.8f}")
    print(f"  1/α = {1/alpha_final:.2f}")
    print(f"  Отклонение от α_exp = {abs(alpha_final - ALPHA_EXP)/ALPHA_EXP*100:.2f}%")
    
    return {
        'Gamma_star': best_Gamma,
        'J_t_MeV': J_t_MeV,
        'E_mon_MeV': J_t_MeV * E_mon,
        'L': L_final,
        'alpha_pred': alpha_final,
        'diff_pct': abs(alpha_final - ALPHA_EXP) / ALPHA_EXP * 100
    }


