# ШАГ 2: ВЫЧИСЛЕНИЕ J_t ИЗ УСЛОВИЯ САМОСОГЛАСОВАНИЯ
# ═══════════════════════════════════════════════════════════════════

def find_Jt_from_selfconsistency(Gamma=0.91):
    """
    Вычисление J_t из условия самосогласования:
    
    α_pred(J_t, Γ) = α_exp
    
    При заданном Γ, находим J_t такое, что α_pred = α_exp.
    
    Это превращает J_t из свободного параметра в ВЫЧИСЛЯЕМУЮ величину.
    """
    # Целевое L из α_exp:
    L_target = PT_ERROR / (4 * math.pi * ALPHA_EXP)  # ≈ 7.13
    
    # L = J_t·E_mon(Γ)/m_e
    # → J_t = L_target · m_e / E_mon(Γ)
    
    E_mon, _ = compute_Lambda_Ze_from_monopole(Gamma, 1.0)
    
    # E_mon в единицах J_t = 1
    # J_t (в МэВ) = L_target · m_e / E_mon(Γ, J_t=1)
    
    J_t_MeV = L_target * M_E / E_mon
    
    # Проверка
    L_check = J_t_MeV * E_mon / M_E
    
    print(f"  Γ = {Gamma:.3f}")
    print(f"  E_mon(Γ) = {E_mon:.4f} J_t")
    print(f"  L_target = {L_target:.2f}")
    print(f"  J_t = {J_t_MeV:.4f} МэВ")
    print(f"  Проверка L = J_t·E_mon/m_e = {L_check:.2f}")
    
    # Физическая интерпретация J_t
    print(f"\n  Физический смысл J_t = {J_t_MeV:.2f} МэВ:")
    print(f"  Это ~удвоенная масса пиона (m_π ≈ 140 МэВ)")
    print(f"  или ~масса мюона (m_μ ≈ 106 МэВ)")
    print(f"  или характерный масштаб ядерных сил (~100 МэВ)")
    print(f"  или масштаб киральной симметрии в КХД (~4πf_π ≈ 1.2 ГэВ)")
    
    return J_t_MeV


