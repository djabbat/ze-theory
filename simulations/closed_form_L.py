PT_ERROR = (2 - LN2) / 2          # 0.6534
ALPHA_EXP = 1 / 137.035999084     # CODATA 2018

# Физические константы
HBAR_C = 197.3269804  # МэВ·фм
M_E = 0.510998950      # МэВ
